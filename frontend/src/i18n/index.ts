const saved = localStorage.getItem('maskbox.locale')
const system = navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
export const currentLocale = (saved === 'zh' || saved === 'en' ? saved : system) as AppLocale

export const i18n = createI18n({
  legacy: false,
  locale: currentLocale,
  fallbackLocale: 'zh',
  messages: { zh, en },
})

export function setLocale(locale: AppLocale): void {
  localStorage.setItem('maskbox.locale', locale)
  i18n.global.locale.value = locale
  document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en'
}
